-- M128 — состояние доставки «перехвачено»: граница тестового контура наружу.
--
-- Зачем. Доставка вебхуков — единственный живой канал платформы во внешний
-- мир: почта локальная (MAIL_TRANSPORT=none), платежи в тестовом режиме, ЯМ не
-- подключена, а вот подписчик с адресом https://… получает настоящий POST.
-- Пока проверки шли руками, это не всплывало; с тестовыми сессиями сценарий
-- «прогон дёрнул событие → ушёл запрос настоящему потребителю» становится
-- обычным делом.
--
-- Решение владельца (2026-09-21): «Закрой живую отправку вебхуков наружу.
-- Нельзя считать отсутствие рабочих данных в БД достаточной защитой от
-- внешних действий».
--
-- Что делает миграция: разрешает доставке состояние `withheld` — «наружу не
-- отправлено, потому что контур не выпускает». Это НЕ ошибка доставки:
-- `failed` означает «пробовали и не вышло», и смешивать их нельзя — иначе
-- очередь начнёт ретраить то, что отправлять запрещено, а в отчёте о
-- проблемах интеграции появится шум.
--
-- Причина хранится строкой: через месяц «почему не ушло» должно читаться из
-- записи, а не выводиться из конфигурации того дня.

ALTER TABLE integration.webhook_deliveries
    DROP CONSTRAINT IF EXISTS webhook_deliveries_status_check;

ALTER TABLE integration.webhook_deliveries
    ADD CONSTRAINT webhook_deliveries_status_check
    CHECK (status IN ('queued', 'delivered', 'failed', 'exhausted', 'withheld'));

ALTER TABLE integration.webhook_deliveries
    ADD COLUMN IF NOT EXISTS withheld_reason TEXT
    CHECK (withheld_reason IS NULL OR length(btrim(withheld_reason)) BETWEEN 3 AND 200);

COMMENT ON COLUMN integration.webhook_deliveries.withheld_reason IS
    'Почему доставка не ушла наружу. Заполняется только при status = withheld; '
    'пусто у всех остальных состояний.';

-- Состояние конечное: перехваченная доставка не стоит в очереди и не ждёт
-- следующей попытки. Частичный индекс очереди уже отбирает queued/failed —
-- добавлять withheld в него нельзя, иначе она попадёт в выборку на отправку.

