-- =============================================================================
-- M122 — раздел «Пользователи» в административном кабинете: право видеть
-- контактные данные и индексы под список.
--
-- Почему право отдельное. Контакты хранятся зашифрованными, и наружу до сих
-- пор уходили только маски — даже владельцу (`identity.service.getCurrentUser`).
-- Карточка пользователя обязана показать администратору контакт целиком:
-- письмо о регистрации прямо обещает «контактные данные видны в карточке под
-- правами». «Под правами» — это и есть отдельное полномочие из каталога M097,
-- а не побочный эффект роли: раскрытие персональных данных не должно быть
-- незаметным следствием входа в админку.
--
-- Что даёт полномочие ПОМИМО роли. `app.has_capability` пропускает
-- администратора всегда — это правило M097, и здесь оно уместно: администратор
-- и есть тот, кому карточка адресована. Полномочие отделяет от него
-- организатора: список и карточку он видит, контакты — нет.
--
-- Раскрытие пишется в журнал отдельным событием. Просмотр списка не пишется:
-- журнал, в который попадает каждое открытие экрана, перестают читать.
-- =============================================================================

-- ------------------------------------------------- полномочие «видеть контакты»
INSERT INTO identity.staff_capabilities
    (code, section, action, title, description, requires_assignment, sort_order) VALUES
    ('identity.user_contacts.view', 'Пользователи', 'view',
     'Видеть контактные данные',
     'Раскрывать полный адрес электронной почты и телефон в карточке пользователя. '
     'Без полномочия карточка показывает только маску. Каждое раскрытие попадает в журнал.',
     false, 10)
ON CONFLICT (code) DO NOTHING;

-- ------------------------------------------------------------ событие журнала
INSERT INTO audit.event_type_registry (verb, description, actor_roles_allowed) VALUES
    ('identity.user_contacts.revealed',
     'Администратор раскрыл контактные данные пользователя',
     ARRAY['admin'])
ON CONFLICT (verb) DO NOTHING;

-- ------------------------------------------------------------------- индексы
-- Список администратора сортируется по дате регистрации (умолчание) и по
-- имени. Без индексов каждая страница означала бы сортировку всей таблицы.
CREATE INDEX IF NOT EXISTS users_created_at_desc
    ON identity.users (created_at DESC, id DESC) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS users_display_name_sort
    ON identity.users (lower(display_name), id) WHERE deleted_at IS NULL;

COMMENT ON INDEX identity.users_created_at_desc IS
    'Страницы списка пользователей в админке (M122): порядок по умолчанию.';
COMMENT ON INDEX identity.users_display_name_sort IS
    'Сортировка списка пользователей по имени (M122). Поиск по части имени идёт '
    'последовательным сканом — ILIKE с ведущим шаблоном индекс не использует, и на '
    'масштабе платформы это дешевле, чем поддерживать триграммный индекс.';
