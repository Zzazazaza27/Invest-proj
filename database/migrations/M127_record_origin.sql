-- =============================================================================
-- M127 — происхождение записи: откуда взялась учётная запись и проект.
--
-- Задача, которую это решает. На стенде 851 учётная запись, живых из них
-- полтора десятка: остальное — следы браузерных проходов и нагрузочных
-- прогонов, каждый из которых заводит себе нового человека при каждом
-- запуске. Список, в котором 99% мусора, нельзя использовать по назначению.
--
-- Почему ПРОИСХОЖДЕНИЕ, а не «тип аккаунта». Метку вида «рабочий / тестовый»
-- ставят руками — и перестают ставить на второй неделе; поле наполовину
-- пустое врёт убедительнее, чем его отсутствие. Происхождение же указывает
-- ТОТ, КТО СОЗДАЁТ запись, в момент создания: забыть его нельзя, это часть
-- вставки.
--
-- Почему не по домену почты (@test.local). Адрес хранится зашифрованным, в
-- SQL его не видно; слепой индекс отвечает только на вопрос о полном
-- совпадении. Дешёвый обходной путь закрыт устройством системы.
--
-- Значение `staff_check` — не выдумка «на будущее»: владелец назвал случай,
-- когда проверочные учётные записи заводятся на БОЕВОМ контуре, потому что
-- часть проблем на тестовой среде не воспроизводится. Такие записи должны
-- отличаться от настоящих людей и при этом НЕ попадать под автоматическую
-- уборку.
--
-- Что это поле НЕ даёт: права. Оно ничего не разрешает и не запрещает, на
-- доступ не влияет и в политиках RLS не участвует. Это признак для отбора и
-- уборки, и только.
-- =============================================================================

-- ------------------------------------------------------------- учётные записи
ALTER TABLE identity.users
    ADD COLUMN IF NOT EXISTS origin TEXT NOT NULL DEFAULT 'self_registration'
    CHECK (origin IN (
        'self_registration',  -- человек зарегистрировался сам
        'invite',             -- приглашение администратора (отложено, значение занято заранее)
        'seed_demo',          -- демонстрационный комплект
        'seed_acceptance',    -- обстановка приёмки
        'staff_check',        -- проверочная запись сотрудника, в том числе на бою
        'render_check',       -- браузерный проход
        'load_test',          -- нагрузочный прогон
        'unknown'             -- заведено до появления этого поля
    ));

COMMENT ON COLUMN identity.users.origin IS
    'Откуда взялась запись (M127). Ставит тот, кто её создаёт; на права не влияет. '
    'Значения render_check и load_test — единственные, которые вправе удалять уборка.';

-- Отбор в списке администратора идёт по этому полю на каждой странице.
CREATE INDEX IF NOT EXISTS users_origin ON identity.users (origin) WHERE deleted_at IS NULL;

-- --------------------------------------------------------------------- проекты
--
-- Проект НЕ спрашивают о происхождении отдельно: он наследует его у того, кто
-- создал. Проход, заведённый как `render_check`, создаёт проекты того же
-- происхождения — и вычищаются они вместе, а не по отдельности. Спрашивать
-- дважды значило бы завести второе место правды об одном и том же.
ALTER TABLE lab.projects
    ADD COLUMN IF NOT EXISTS origin TEXT NOT NULL DEFAULT 'self_registration'
    CHECK (origin IN (
        'self_registration', 'invite', 'seed_demo', 'seed_acceptance',
        'staff_check', 'render_check', 'load_test', 'unknown'
    ));

COMMENT ON COLUMN lab.projects.origin IS
    'Происхождение проекта (M127): наследуется у создателя. На видимость и права не влияет.';

CREATE INDEX IF NOT EXISTS projects_origin ON lab.projects (origin) WHERE deleted_at IS NULL;

