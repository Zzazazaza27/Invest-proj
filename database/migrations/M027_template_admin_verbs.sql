-- M027 — журнальные глаголы админского управления текстами уведомлений
--
-- Реестр verb'ов fail-closed (M001): событие с незарегистрированным глаголом не
-- пишется вовсе, и запись действия админа упала бы вместе с самим действием.
-- Поэтому глагол регистрируется ДО появления маршрута, а не вместе с ним.
--
-- Роль в списке ровно одна: тексты, уходящие пользователям, правит только
-- администратор — организатору этого не требуется, а расширять список «на
-- всякий случай» значит расширять поверхность без причины.
-- =============================================================================

INSERT INTO audit.event_type_registry (verb, description, actor_roles_allowed) VALUES
    ('comms.template.updated', 'Изменён текст шаблона уведомления', ARRAY['admin'])
ON CONFLICT (verb) DO NOTHING;
