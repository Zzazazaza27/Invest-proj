-- =============================================================================
-- M033 — раздельные состояния outbox и аренда строк между экземплярами
--
-- Две находки внешнего аудита, обе подтверждены чтением кода.
--
-- 1. Потеря доставок (CODE-04). Публикатор помечал событие опубликованным, а
--    затем ставил доставки подписчикам. Ошибка постановки только логировалась,
--    и комментарий обещал, что «доставку подхватит следующий проход». Проход
--    выбирает строки с `published_at IS NULL` — то есть уже опубликованное
--    событие он не увидит НИКОГДА. Одна временная недоступность контура
--    интеграции означала безвозвратную потерю внешних уведомлений, причём
--    молча.
--
--    Лечится не порядком действий, а состоянием: публикация в брокер и
--    постановка доставок — разные факты, и у них разные отметки. Обратный
--    порядок («сначала доставки») связал бы публикацию в NATS с доступностью
--    интеграционной БД, а это уже потеря доступности вместо потери данных.
--
-- 2. Аренда (CODE-05). `FOR UPDATE SKIP LOCKED` держит строку только до конца
--    транзакции, а транзакция закрывалась ДО публикации. Второй экземпляр
--    немедленно забирал те же строки: возможны двойная публикация и гонка
--    счётчиков. Колонка `locked_at` существовала, но в условии выборки не
--    участвовала — то есть не делала ничего.
--
--    Аренда с явным сроком: строка занята до `locked_until`, и чужой экземпляр
--    её не берёт. Просроченная аренда освобождается сама — упавший экземпляр
--    не блокирует очередь навсегда.
-- =============================================================================

ALTER TABLE audit.outbox_events
    ADD COLUMN IF NOT EXISTS fanout_completed_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS locked_until TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS locked_by TEXT;

COMMENT ON COLUMN audit.outbox_events.fanout_completed_at IS
    'Момент постановки доставок подписчикам. Отдельно от published_at: '
    'публикация в брокер и постановка доставок — разные факты (M033).';
COMMENT ON COLUMN audit.outbox_events.locked_until IS
    'Срок аренды строки экземпляром публикатора. Просроченная аренда '
    'освобождается сама: упавший экземпляр не держит очередь.';

-- Уже опубликованные к этому моменту события считаем разосланными: доставки по
-- ним либо поставлены, либо потеряны прежним поведением, и «переставить» их
-- задним числом нельзя — дубли ушли бы получателям как новые события.
UPDATE audit.outbox_events
   SET fanout_completed_at = published_at
 WHERE published_at IS NOT NULL AND fanout_completed_at IS NULL;

-- Выборка неопубликованных с учётом аренды.
CREATE INDEX IF NOT EXISTS outbox_pending_lease
    ON audit.outbox_events (next_attempt_at, created_at)
    WHERE published_at IS NULL;

-- Выборка опубликованных, но не разосланных: это и есть очередь повтора,
-- которой раньше не существовало.
CREATE INDEX IF NOT EXISTS outbox_pending_fanout
    ON audit.outbox_events (published_at)
    WHERE published_at IS NOT NULL AND fanout_completed_at IS NULL;

GRANT SELECT, INSERT, UPDATE ON audit.outbox_events TO app_backend;
