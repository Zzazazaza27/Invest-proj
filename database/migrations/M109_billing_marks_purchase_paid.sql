-- M109 — денежный контур отмечает покупку оплаченной.
--
-- Подтверждение оплаты приходит уведомлением провайдера, а обрабатывается под
-- ролью `app_billing` (M009: роль приложения деньги не пишет). Отметить при
-- этом покупку оплаченной было нечем: прав на `billing.round_purchases` у
-- денежного контура не было вовсе.
--
-- Разнести это на две транзакции нельзя: платёж оказался бы подтверждён, а
-- покупка — нет, и восстанавливать связь пришлось бы руками. Поэтому право
-- даётся ровно там, где факт и возникает.
--
-- Что при этом НЕ ослабевает: снимок покупки и её суммы остаются
-- неизменяемыми (триггер M103), метка тестовой оплаты по-прежнему не
-- снимается, а допуск к открытию платного раунда по-прежнему её учитывает
-- (M107). Денежный контур может перевести покупку в оплаченную — и только.

GRANT SELECT, UPDATE ON billing.round_purchases TO app_billing;

CREATE POLICY round_purchases_billing ON billing.round_purchases FOR SELECT
    TO app_billing USING (true);
CREATE POLICY round_purchases_billing_update ON billing.round_purchases FOR UPDATE
    TO app_billing USING (true) WITH CHECK (true);

COMMENT ON POLICY round_purchases_billing_update ON billing.round_purchases IS
    'Денежный контур отмечает покупку оплаченной по подтверждённому платежу (M109). Снимок, '
    'суммы и метка тестовой оплаты защищены триггерами и этой политикой не открываются.';
