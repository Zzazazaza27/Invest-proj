-- =============================================================================
-- M058 — уточнение видимости неподтверждённых материалов (доводка M056)
--
-- M056 закрыл чтение неподтверждённых материалов ВСЕМ, включая автора билета.
-- Зонд подделки формата поймал следствие: `finalizeUpload` читает свою строку
-- (`SELECT ... FOR UPDATE`) ДО того, как проставит `uploaded_at`, — политика
-- её скрывала, и подтверждение отвечало 404 вместо работы. То есть «вторая
-- линия» закрыла не только утечку, но и сам путь загрузки.
--
-- Граница проходит не по факту подтверждения, а по ЛИЦУ: незавершённый билет
-- виден ТОЛЬКО тому, кто его выдал (он его и подтверждает), и админу.
-- Остальным участникам проекта, рецензентам и любым внешним читателям
-- неподтверждённый материал по-прежнему не виден — ровно то, чего требовала
-- находка аудита (метаданные s3_key/тип/версия не утекают).
-- =============================================================================

DROP POLICY materials_member ON lab.project_materials;
CREATE POLICY materials_member ON lab.project_materials FOR ALL TO app_backend
    USING (
        (lab.is_project_member(project_id, app.current_user_id())
         OR app.has_role('admin') OR app.has_role('organizer'))
        AND (
            uploaded_at IS NOT NULL
            -- Свой незавершённый билет виден его автору: подтверждение
            -- загрузки читает эту же строку до простановки uploaded_at.
            OR uploaded_by = app.current_user_id()
            OR app.has_role('admin')
        ))
    WITH CHECK (lab.is_project_member(project_id, app.current_user_id())
                OR app.has_role('admin'));

COMMENT ON POLICY materials_member ON lab.project_materials IS
    'Участник проекта видит подтверждённые материалы; незавершённый билет — '
    'только его автор и админ (M056 + доводка M058).';
