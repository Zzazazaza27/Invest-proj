-- =============================================================================
-- M047 — инварианты состояния материала переносятся в схему
--
-- Находка внешнего аудита (CODE-05). «Машина состояний» загрузки — это одно
-- поле `uploaded_at`: NULL значит «билет выдан, файла ещё нет», непустое —
-- «загрузка подтверждена». Всё остальное держалось на аккуратности кода:
-- подтверждение обязано было заодно проставить размер, а ссылка на продукт —
-- считаться загруженной сразу. Ни одно из этих правил схема не проверяла, и
-- любая новая точка записи могла оставить материал в состоянии, которого не
-- бывает: «подтверждён, но неизвестно что».
--
-- Здесь оба правила становятся ограничениями. Инвариант, выраженный в схеме,
-- нельзя обойти ни ошибкой в сервисе, ни ручным UPDATE в консоли.
--
-- Почему NOT VALID. Ограничения действуют для всех новых и изменяемых строк, но
-- существующие не перепроверяются: в таблице есть материалы, подтверждённые до
-- появления отпечатка объекта (M044), и падение миграции на них ничего бы не
-- исправило — данных, которых не собирали, задним числом не появится. Проверка
-- накопленного — отдельная задача (VALIDATE CONSTRAINT), внесена в TODO.
-- =============================================================================

-- Подтверждённая загрузка в хранилище обязана знать размер объекта. Это ровно
-- то, что делает `finalizeUpload`, читая его из ответа хранилища; ограничение
-- фиксирует, что иначе быть не может.
ALTER TABLE lab.project_materials
    ADD CONSTRAINT project_materials_confirmed_has_size
    CHECK (s3_key IS NULL OR uploaded_at IS NULL OR size_bytes IS NOT NULL)
    NOT VALID;

-- Ссылка на продукт не проходит через хранилище: момент её создания и есть
-- момент загрузки. Материал этого типа без отметки — состояние, в котором его
-- не видит ни владелец, ни рецензент, и при этом его убирает уборщик.
ALTER TABLE lab.project_materials
    ADD CONSTRAINT project_materials_link_is_uploaded
    CHECK (type <> 'product_link' OR uploaded_at IS NOT NULL)
    NOT VALID;

COMMENT ON CONSTRAINT project_materials_confirmed_has_size ON lab.project_materials IS
    'Подтверждённый объект хранилища знает свой размер. Инвариант в схеме, а не '
    'в коде: обойти его новой точкой записи нельзя (CODE-05, M047).';

COMMENT ON CONSTRAINT project_materials_link_is_uploaded ON lab.project_materials IS
    'Ссылка на продукт загружена в момент создания — хранилища в её пути нет '
    '(CODE-05, M047).';
