-- =============================================================================
-- M051 — contract-миграция: удаление `identity.consents.ip_hash`
--        + проверка накопленных строк по второму инварианту M047
--
-- Первая половина. M043 (SEC-16) переименовала смысл: хеш идентификатора
-- запроса переехал в `request_trace_hash`, старая колонка перестала быть
-- обязательной и ждала, пока в неё перестанут писать. Писали четверо — оба
-- тестовых хелпера и оба сид-скрипта; все четверо переведены на новую колонку
-- в этой же фазе (Ф28), сверено grep'ом по репозиторию. Перед удалением
-- миграция сама проверяет, что перенос M043 ничего не потерял: каждая строка
-- со старым значением обязана нести то же значение в новой колонке. Если это
-- не так — исключение, и колонка остаётся на месте.
--
-- Вторая половина. `project_materials_confirmed_has_size` оставалась NOT VALID
-- из-за 25 строк, подтверждённых до M044 без размера. M050 назвала условие
-- закрытия: «сверить объекты с хранилищем и проставить фактический размер».
-- Это сделано скриптом `scripts/backfill-material-sizes.mjs`: все 25 объектов
-- найдены в хранилище живыми, размер взят из ответа HEAD (content-length), то
-- есть ИЗМЕРЕН, а не выдуман. Нарушающих строк не осталось — ограничение
-- валидируется. На базе, где нарушающие строки ещё есть, VALIDATE упадёт —
-- это правильно: сначала backfill, потом миграция.
-- =============================================================================
-- migrate:contract

DO $$
DECLARE
    v_lost BIGINT;
BEGIN
    SELECT count(*) INTO v_lost
      FROM identity.consents
     WHERE ip_hash IS NOT NULL
       AND (request_trace_hash IS NULL OR request_trace_hash <> ip_hash);
    IF v_lost > 0 THEN
        RAISE EXCEPTION
            'M051: % строк(и) identity.consents несут в ip_hash значение, '
            'которого нет в request_trace_hash — перенос M043 неполон, '
            'удаление колонки потеряло бы данные', v_lost;
    END IF;
END $$;

ALTER TABLE identity.consents DROP COLUMN ip_hash;

ALTER TABLE lab.project_materials
    VALIDATE CONSTRAINT project_materials_confirmed_has_size;
