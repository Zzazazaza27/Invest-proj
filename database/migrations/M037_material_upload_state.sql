-- =============================================================================
-- M037 — состояние загрузки материала и защита от бесконтрольного роста
--
-- Находка внешнего аудита (SEC-14/CODE-10): запись в `lab.project_materials`
-- создаётся ВМЕСТЕ с выдачей билета на загрузку, то есть до того, как файл
-- вообще появился в хранилище. Отменённая или неудавшаяся загрузка навсегда
-- оставляет строку, которая выглядит как материал проекта. Квоты при этом нет
-- никакой: авторизованный пользователь выпускает билеты и создаёт строки
-- сколько угодно.
--
-- Разделение состояний: `uploaded_at` отмечает ФАКТ загрузки, подтверждённый
-- обращением к хранилищу. Пока отметки нет, материал существует только как
-- намерение — и наружу как материал не выдаётся.
--
-- Почему не «удалять строку при отмене»: клиент об отмене не сообщает, а без
-- строки нельзя ни проверить квоту, ни убрать за собой объект в хранилище.
-- =============================================================================

ALTER TABLE lab.project_materials
    ADD COLUMN IF NOT EXISTS uploaded_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS size_bytes BIGINT CHECK (size_bytes IS NULL OR size_bytes >= 0);

COMMENT ON COLUMN lab.project_materials.uploaded_at IS
    'Момент подтверждённой загрузки: сервер убедился, что объект есть в хранилище. '
    'NULL — билет выдан, но файла нет (M037).';

-- Ссылки на продукт загрузки не требуют: они «загружены» в момент создания.
UPDATE lab.project_materials
   SET uploaded_at = created_at
 WHERE type = 'product_link' AND uploaded_at IS NULL;

-- Материалы, созданные до этой миграции, считаются загруженными: проверить их
-- задним числом нечем, а объявить несуществующими — потерять настоящие данные.
UPDATE lab.project_materials
   SET uploaded_at = created_at
 WHERE uploaded_at IS NULL;

-- Незавершённые загрузки: по этому индексу их находит уборка.
CREATE INDEX IF NOT EXISTS project_materials_pending_upload
    ON lab.project_materials (created_at)
    WHERE uploaded_at IS NULL;
