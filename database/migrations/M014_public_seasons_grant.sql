-- =============================================================================
-- M014 — доступ публичной роли к метроному сезона
--
-- M007 выдал app_public_read право SELECT на seasons.seasons, но не USAGE на
-- саму схему: без него запрос падает на «permission denied for schema seasons»
-- ещё до проверки политик. Право на таблицу без права на схему — это право,
-- которым нельзя воспользоваться.
--
-- Публичным является ровно факт «идёт ли приём заявок»: по нему основатель
-- понимает, имеет ли смысл готовить заявку. Ни состав сезона, ни конфигурация
-- воронки сюда не входят — политика seasons_public_read отдаёт только строки
-- самой таблицы сезонов, а колонки настроек публичной роли не нужны.
-- =============================================================================

GRANT USAGE ON SCHEMA seasons TO app_public_read;
