-- =============================================================================
-- M043 — согласие: честное имя поля вместо `ip_hash`
--
-- Находка внешнего аудита (SEC-16). Колонка называется `ip_hash`, но код клал в
-- неё хеш `traceId` — идентификатора запроса, а не адреса. Утечки здесь нет:
-- значение и так хешировано. Неверно другое — СМЫСЛ записи. Запись о согласии
-- существует ради юридического доказательства, и поле с именем `ip_hash`
-- читается проверяющим как «с какого адреса дано согласие». Такого
-- доказательства в ней нет и никогда не было.
--
-- Выбрана честная модель из двух названных аудитом: не собирать адрес и назвать
-- поле тем, что в нём лежит. Довериться адресу здесь всё равно нельзя — граница
-- прокси не доказана (SEC-03 остаётся открытой), а значит «адрес» был бы
-- значением из заголовка, которое подставляет клиент. Хеш идентификатора
-- запроса связывает согласие с записью журнала — это реальное свойство, и оно
-- теперь называется своим именем.
--
-- Фаза expand: новая колонка добавляется, старая остаётся и лишь перестаёт быть
-- обязательной. Удаление `ip_hash` — отдельная contract-миграция после того,
-- как ни один экземпляр в неё не пишет (Database_Launch.md §16); задача внесена
-- в TODO.
-- =============================================================================

ALTER TABLE identity.consents
    ADD COLUMN IF NOT EXISTS request_trace_hash BYTEA;

-- Значения переносятся как есть: в старой колонке лежало ровно это — хеш
-- идентификатора запроса, а не адреса.
--
-- Триггер `consents_immutable` запрещает UPDATE строк согласия, и это верно:
-- запись о согласии — юридическое доказательство, её нельзя править задним
-- числом. Здесь триггер снимается на время ОДНОЙ операции переноса и ставится
-- обратно в той же транзакции. Содержимое при этом не меняется: значение
-- копируется байт в байт из соседней колонки той же строки, ни одно поле
-- самого согласия (вид, версия, момент принятия) не затрагивается.
ALTER TABLE identity.consents DISABLE TRIGGER consents_immutable;

UPDATE identity.consents
   SET request_trace_hash = ip_hash
 WHERE request_trace_hash IS NULL;

ALTER TABLE identity.consents ENABLE TRIGGER consents_immutable;

-- Старое поле перестаёт быть обязательным: новый код в него не пишет, а
-- удалять его в этой же миграции нельзя — во время выкладки ещё работают
-- экземпляры, которые о новой колонке не знают.
ALTER TABLE identity.consents
    ALTER COLUMN ip_hash DROP NOT NULL;

COMMENT ON COLUMN identity.consents.request_trace_hash IS
    'HMAC идентификатора запроса, в котором дано согласие. Связывает запись с '
    'журналом обращений. НЕ является ни адресом, ни идентификатором личности и '
    'не доказывает канал получения согласия (SEC-16, M043).';

COMMENT ON COLUMN identity.consents.ip_hash IS
    'УСТАРЕЛО. Несмотря на имя, всегда содержала хеш идентификатора запроса, а '
    'не адреса. Заменена на request_trace_hash; удаляется отдельной '
    'contract-миграцией (SEC-16, M043).';
