-- =============================================================================
-- M042 — рубеж токенов сервисного аккаунта: приостановка действует сразу
--
-- Находка внешнего аудита (SEC-08). Приостановка аккаунта и ротация секрета
-- закрывали только ВЫДАЧУ новых токенов. Уже выданный токен самодостаточен и
-- живёт до `exp` — по конфигурации до часа. То есть на украденный токен
-- администратор не мог отреагировать вовсе: он нажимал «приостановить», а
-- чужая система продолжала работать ещё час. Прежний код это прямо
-- документировал как открытый долг.
--
-- Механика — та же, что у пользовательских сессий (M035): рубеж. У аккаунта
-- появляется счётчик `token_epoch`, его значение кладётся в токен при выдаче и
-- сверяется на каждом запросе. Приостановка и ротация секрета увеличивают
-- счётчик, и все ранее выданные токены перестают совпадать.
--
-- Почему не реестр отозванных (M038), как у пользователей: там отзывается ОДИН
-- токен из многих, здесь — все токены одного аккаунта разом. Рубеж выражает
-- ровно это и не требует ни одной новой строки на выдачу.
--
-- Проверка на запросе идёт под ролью `app_integration`, у которой политика
-- чтения аккаунтов уже ограничена `status = 'active'` (M010): приостановленный
-- аккаунт просто исчезает из выборки, и токен отклоняется независимо от
-- счётчика. Счётчик закрывает второй случай — ротацию секрета без приостановки.
-- =============================================================================

ALTER TABLE integration.service_accounts
    ADD COLUMN IF NOT EXISTS token_epoch INTEGER NOT NULL DEFAULT 1
        CHECK (token_epoch > 0);

COMMENT ON COLUMN integration.service_accounts.token_epoch IS
    'Рубеж токенов. Увеличивается при приостановке и ротации секрета: все ранее '
    'выданные токены перестают проходить проверку (SEC-08, M042).';

-- Существующие аккаунты начинают с первого рубежа. Отдельного backfill не
-- требуется: DEFAULT проставляет 1 всем имеющимся строкам, а токены, выданные
-- до этой миграции, счётчика не содержат и отвергаются как «без рубежа».
