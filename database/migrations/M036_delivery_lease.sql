-- =============================================================================
-- M036 — аренда строк очереди доставки вебхуков
--
-- Находка внешнего аудита (SEC-19): очередь доставок берётся `FOR UPDATE
-- SKIP LOCKED`, но блокировка отпускается вместе с транзакцией — то есть ДО
-- самого HTTP-запроса. Два экземпляра core берут одну доставку и отправляют её
-- получателю одновременно.
--
-- Заголовок `Unicorn-Event-Id` позволяет получателю дедуплицировать, но
-- перекладывать гарантию на чужую систему нельзя: она может быть проще, чем мы
-- предполагаем, а побочный эффект у неё — настоящий.
--
-- То же лечение, что для очереди публикации (M033): аренда с явным сроком.
-- Просроченная освобождается сама, поэтому упавший экземпляр не держит очередь.
-- =============================================================================

ALTER TABLE integration.webhook_deliveries
    ADD COLUMN IF NOT EXISTS locked_until TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS locked_by TEXT;

COMMENT ON COLUMN integration.webhook_deliveries.locked_until IS
    'Срок аренды строки экземпляром доставки. Чужой экземпляр строку не берёт; '
    'просроченная аренда освобождается сама (M036).';

-- Индекс под фактическое условие выборки: статус, срок повтора и аренда.
CREATE INDEX IF NOT EXISTS webhook_deliveries_lease
    ON integration.webhook_deliveries (next_retry_at, created_at)
    WHERE status IN ('queued', 'failed');
