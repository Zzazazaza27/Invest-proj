-- M136: у запуска появляется СЕКРЕТ, а не только идентификатор.
--
-- ЗАЧЕМ. С M133 право назвать запись следом прогона подтверждалось
-- идентификатором действующей тестовой сессии. Опыт 2026-09-23 показал, что
-- этого мало: идентификатор не секрет. Он печатается прогонами в консоль,
-- виден в админке, попадает в отчёты запусков и в журнал. Посторонний,
-- узнавший его, регистрировался с этим идентификатором и получал и
-- происхождение `render_check`, и место в перечне ЧУЖОГО запуска — то есть
-- мог подвести свои записи под чужую уборку и засорить чужой перечень.
--
-- Проверено фактом: HTTP 201, origin = render_check, объект в перечне чужой
-- сессии.
--
-- ЧТО МЕНЯЕТСЯ. У сессии появляется токен: случайные 32 байта, которые
-- сервер отдаёт ОДИН раз — тому, кто сессию создал, вместе с ответом на её
-- создание. В базе лежит только SHA-256 от него. Публичный маршрут
-- регистрации принимает теперь токен, а не идентификатор: знание того, что
-- «запуск с таким-то id идёт», больше ничего не даёт.
--
-- ПОЧЕМУ ХЕШ, А НЕ САМ ТОКЕН. Тот же довод, что у ссылок восстановления
-- пароля (M-серия Ф51): содержимое базы не должно давать доступ. Утечка
-- дампа не превращается в право создавать записи от имени чужих запусков.
ALTER TABLE testing.sessions
    ADD COLUMN IF NOT EXISTS run_token_hash BYTEA;

COMMENT ON COLUMN testing.sessions.run_token_hash IS
    'SHA-256 секрета запуска. Сам секрет отдаётся один раз при создании '
    'сессии и в базе не хранится: идентификатор сессии не секрет, а право '
    'создавать записи от её имени — секрет.';

-- Сессии, заведённые до этой миграции, токена не имеют: с ними регистрация
-- по токену просто не сработает. Это правильный исход — старый способ
-- подтверждения права перестаёт действовать, а не продолжает жить рядом.

/**
 * Найти ДЕЙСТВУЮЩИЙ запуск по секрету.
 *
 * Возвращает идентификатор сессии либо NULL. Отвечает только на вопрос
 * «есть ли активный запуск с таким секретом»: ни заголовка, ни владельца, ни
 * факта существования неактивной сессии наружу не уходит.
 *
 * Функция-владелец: спрашивает публичный маршрут регистрации, у которого нет
 * пользователя в контексте, а политики testing.sessions построены на нём.
 */
CREATE OR REPLACE FUNCTION testing.run_by_token(p_token_hash BYTEA)
RETURNS UUID
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = testing, pg_temp
AS $$
DECLARE
    v_id UUID;
BEGIN
    IF p_token_hash IS NULL THEN
        RETURN NULL;
    END IF;
    SELECT id INTO v_id
      FROM testing.sessions
     WHERE status = 'active' AND run_token_hash = p_token_hash;
    RETURN v_id;
END;
$$;

COMMENT ON FUNCTION testing.run_by_token(BYTEA) IS
    'Идентификатор действующего запуска по секрету. Знание идентификатора '
    'сессии права не даёт — нужен секрет, выданный её создателю.';

GRANT EXECUTE ON FUNCTION testing.run_by_token(BYTEA) TO app_backend;
