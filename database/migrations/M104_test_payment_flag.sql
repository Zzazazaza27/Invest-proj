-- M104 — флаг тестового подтверждения оплаты покупки запуска раунда.
--
-- Сквозной сценарий нужно пройти руками локально, но «подтвердить оплату» без
-- денег — это ровно то, чем нельзя пользоваться в рабочем окружении. Поэтому
-- действие закрыто ТРЕМЯ независимыми условиями, и ни одно не является
-- следствием другого:
--
--   1. роль администратора;
--   2. этот флаг — выключен по умолчанию;
--   3. окружение: в production действие отвергается до чтения флага.
--
-- Отдельный флаг, а не `billing.payments.enabled`: тот отвечает за приём
-- НАСТОЯЩИХ платежей, и включать его ради проверки значило бы смешать «денег
-- нет, но сценарий проверяем» с «деньги принимаются».
INSERT INTO audit.feature_flags (key, enabled, rules_jsonb)
VALUES ('billing.test_payment_confirmation', false,
        '{"note":"Тестовое подтверждение оплаты покупки запуска раунда (5.9.7). Денег не двигает; покупка навсегда помечается is_test_payment. Только для локальных и проверочных окружений: в production действие отвергается независимо от флага."}')
ON CONFLICT (key) DO NOTHING;
