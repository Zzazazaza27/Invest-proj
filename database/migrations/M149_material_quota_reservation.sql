-- M149 — квота материалов: резерв места и лимит активных передач (2.1-W03).
--
-- Исправляет правило M148 (замечание Тэнка при приёмке W03). M148 переставала
-- считать загрузку с истёкшей формой и неполученным объектом — и в общем
-- пределе тоже. Истечение формы не доказывает, что передача прекратилась:
-- 49 готовых + такая загрузка → место «освобождается», создаётся и
-- завершается другая (50), затем приходит поздний файл, сверка его завершает
-- — 51 при пределе 50.
--
-- Правило теперь двойное:
--  * ОБЩИЙ ПРЕДЕЛ (50) считает готовые материалы и ВСЕ незавершённые загрузки.
--    Место резервируется при выдаче формы и держится, пока загрузка не
--    закончилась (готово / отклонено / требует вмешательства). Поздний файл
--    поэтому всегда можно завершить, не превысив предел.
--  * ЛИМИТ АКТИВНЫХ ПЕРЕДАЧ (5) считает только незавершённые, у которых форма
--    ещё действует или объект уже получен. Истёкшая форма без объекта
--    освобождает этот лимит — новые передачи можно начинать, — но не место в
--    общем пределе.
--
-- Освобождение места брошенной загрузкой — явная отмена автором (предложение
-- к W04); автоматического освобождения по времени нет.

CREATE OR REPLACE FUNCTION lab.material_counters(p_project_id UUID)
RETURNS TABLE (total BIGINT, pending BIGINT)
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = pg_catalog, lab, pg_temp
AS $$
    SELECT count(*) FILTER (WHERE m.upload_state IN ('ready', 'pending'))::bigint,
           count(*) FILTER (
               WHERE m.upload_state = 'pending'
                 AND (m.object_received_at IS NOT NULL
                      OR (m.upload_expires_at IS NOT NULL AND m.upload_expires_at > now()))
           )::bigint
      FROM lab.project_materials m
     WHERE m.project_id = p_project_id;
$$;

COMMENT ON FUNCTION lab.material_counters(UUID) IS
    'Квота загрузок поверх RLS: total — готовые и все незавершённые (резерв места до '
    'окончания загрузки); pending — активные передачи (форма действует или объект '
    'получен). Брошенная форма освобождает лимит передач, но не место (M149).';
