-- =============================================================================
-- M019 — область действия ключа идемпотентности договора
--
-- В M005 ключ был уникален ГЛОБАЛЬНО. Это давало посторонней стороне рычаг:
-- заняв чужой ключ первой, она заставляла запрос настоящего инвестора
-- падать конфликтом — притом что своего договора он так и не получал, а в
-- ответе видел «операция уже выполнена». Денежный путь не должен зависеть от
-- того, какое значение выбрал другой пользователь.
--
-- Ключ идемпотентности принадлежит инвестору: уникальность считается в паре
-- (investor_id, idempotency_key). Повтор собственной отправки формы по-прежнему
-- не создаёт второго договора — именно ради этого ключ и вводился.
-- =============================================================================

ALTER TABLE investments.investment_agreements
    DROP CONSTRAINT IF EXISTS investment_agreements_idempotency_key_key;

CREATE UNIQUE INDEX IF NOT EXISTS investment_agreements_investor_idempotency
    ON investments.investment_agreements (investor_id, idempotency_key);

COMMENT ON COLUMN investments.investment_agreements.idempotency_key IS
    'Ключ идемпотентности инвестора. Уникален в паре с investor_id: чужой ключ '
    'не может ни заблокировать операцию, ни быть использован как оракул '
    'существования договора.';
