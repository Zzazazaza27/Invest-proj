-- =============================================================================
-- M059 — согласия на публичный контур: документ и граница проекта
--
-- Таблица identity.publication_consents живёт с M002, событие отзыва и срок
-- удаления проекции (15 минут) зафиксированы в контрактах, функция чтения для
-- медиаконтура (integration.active_publication_consent) есть с M010 — а способа
-- ВЫДАТЬ согласие не было: маршрута в ядре не существовало, клиент звал
-- POST /v1/publication-consents и получал 404 (LOW из отчёта Ф48).
--
-- Здесь закрываются две вещи, без которых маршрут писать нельзя:
--
--  1. ДОКУМЕНТ. У каждого согласия есть версия и отпечаток текста
--     (document_version, document_sha256). Брать их из тела запроса — та же
--     ошибка, что стоила Ф49 пятисотки на регистрации: клиент подставляет
--     версию наугад, она не существует, и наружу уходит внутренняя ошибка.
--     Источник правды один — identity.consent_templates; здесь заводится
--     действующая версия документа `pdn_biometric`, которым согласие и
--     оформляется. Съёмка отбора, буткемпа и финала раскрывает изображение и
--     голос — это биометрические ПДн; публичный топ-100 распространяет
--     изображение и имя. Документ на все четыре области один: их различает
--     поле scope самого согласия, а не отдельный текст на каждую.
--
--  2. ГРАНИЦА ПРОЕКТА. Прежняя политика publication_consents_own (M002) была
--     FOR ALL с WITH CHECK `user_id = app.current_user_id()`: проверялось, что
--     человек выдаёт согласие ОТ СЕБЯ, но не то, что он имеет отношение к
--     проекту. То есть любой пользователь мог оставить строку согласия на
--     ЧУЖОЙ проект — а медиаконтур читает эти строки как разрешение снимать.
--     Требование членства переносится в саму политику, а не остаётся только в
--     коде сервиса: политика действует и для прямого доступа к БД.
--
-- Заодно из политик уходит DELETE. Права на удаление у app_backend и не было
-- (GRANT в M002 выдаёт только SELECT/INSERT/UPDATE), но политика FOR ALL
-- описывала удаление как разрешённое — а согласие отменяют отзывом
-- (revoked_at), не удалением строки. Расхождение политики и GRANT'а живёт ровно
-- до того дня, когда кто-нибудь выдаст недостающую привилегию.
-- =============================================================================

-- ------------------------------------- действующая версия документа публикации
--
-- body_sha256 — отпечаток ПЛЕЙСХОЛДЕРА, как и у остальных документов из M011:
-- до production тексты утверждает юрист, и хеши пересчитываются от фактических
-- документов (COMMENT на таблице говорит это же).
INSERT INTO identity.consent_templates (kind, version, locale, body_sha256, s3_key, published_at)
VALUES ('pdn_biometric', 'v1', 'ru-RU', digest('pdn_biometric_v1_placeholder', 'sha256'),
        'legal/pdn_biometric_v1.md', '2026-08-09T00:00:00Z')
ON CONFLICT (kind, version, locale) DO NOTHING;

-- ------------------------------------------------- политики: раздельно по цели
--
-- Одна политика FOR ALL не даёт различать выдачу и отзыв: требование членства
-- нужно на ВЫДАЧЕ, но если оно попадёт и в отзыв, человек, выбывший из проекта,
-- не сможет отозвать собственное согласие на съёмку. Это ровно тот случай,
-- когда отзыв обязан работать всегда.
DROP POLICY publication_consents_own ON identity.publication_consents;

CREATE POLICY publication_consents_select ON identity.publication_consents FOR SELECT
    TO app_backend USING (
        user_id = app.current_user_id()
        OR app.has_role('admin')
        OR app.has_role('organizer'));

-- Выдать согласие может только участник проекта и только от своего имени.
-- Ни admin, ни organizer сюда не попадают намеренно: согласие на съёмку,
-- проставленное администратором за пользователя, не является согласием.
CREATE POLICY publication_consents_grant ON identity.publication_consents FOR INSERT
    TO app_backend WITH CHECK (
        user_id = app.current_user_id()
        AND lab.is_project_member(project_id, app.current_user_id()));

-- Отзыв: свои строки — всегда, admin — по обращению субъекта ПДн (152-ФЗ ст. 9
-- даёт право отозвать согласие; отказ платформы был бы нарушением).
-- WITH CHECK повторяет USING, иначе строку можно было бы переписать на другого
-- владельца тем же UPDATE.
CREATE POLICY publication_consents_revoke ON identity.publication_consents FOR UPDATE
    TO app_backend
    USING (user_id = app.current_user_id() OR app.has_role('admin'))
    WITH CHECK (user_id = app.current_user_id() OR app.has_role('admin'));

COMMENT ON TABLE identity.publication_consents IS
    'Согласия на публичный контур (шов к медиаконтуру Шоу). Append-only по смыслу: '
    'отмена — revoked_at, не DELETE. Документ — identity.consent_templates(pdn_biometric).';
