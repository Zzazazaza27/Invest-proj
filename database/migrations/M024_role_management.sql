-- =============================================================================
-- M024 — управление ролями через API
--
-- До этой миграции роли `admin`, `organizer` и `expert` присваивались
-- оператором напрямую в БД. Само по себе это работало, но не оставляло следа:
-- кто выдал право, кому и когда, в журнале не было — а выдача роли админа это
-- самое весомое изменение прав на платформе.
--
-- Событие с незарегистрированным verb не пишется вовсе (M001, fail-closed),
-- поэтому реестр пополняется здесь, до первой выдачи через API.
-- =============================================================================

INSERT INTO audit.event_type_registry (verb, description, actor_roles_allowed) VALUES
    ('identity.role.granted', 'Пользователю выдана роль',  ARRAY['admin']),
    ('identity.role.revoked', 'У пользователя снята роль', ARRAY['admin'])
ON CONFLICT (verb) DO NOTHING;

-- Подсчёт действующих администраторов выполняется на каждом снятии роли
-- (защита «последний администратор не снимается»), поэтому частичный индекс
-- здесь не оптимизация, а условие того, что проверка не станет дороже самой
-- операции по мере роста числа пользователей.
CREATE INDEX IF NOT EXISTS user_roles_active_by_role
    ON identity.user_roles (role) WHERE revoked_at IS NULL;
