-- M145 — скин платформы как флаг `ui.skin` (решение владельца 2026-09-24).
--
-- Администратор выбирает скин в каталоге «Элементы интерфейса» и применяет
-- его для всей платформы; все восемь интерфейсов читают выбор при загрузке
-- из публичного `GET /v1/features` (поле `skin`).
--
-- Параллельного механизма настроек нет: флаги платформы уже дают всё нужное —
-- запись только администратором с причиной, `updated_by`/`updated_at` и
-- событие журнала `admin.feature_flag.changed`. Значение скина — в
-- `rules_jsonb.value`; `enabled` для этого ключа смысла не имеет и держится
-- `true`, а обычный переключатель флагов этот ключ не меняет (отказ в
-- `setFeatureFlag`).
--
-- Строка заводится со значением по умолчанию `nova` — тем же, что стоит в
-- `data-brand` у `index.html` интерфейсов: применение миграции ничего на
-- экранах не меняет. Уже существующая строка не перезаписывается.

INSERT INTO audit.feature_flags (key, enabled, rules_jsonb)
VALUES ('ui.skin', true,
        '{"value":"nova","note":"Скин всей платформы. Меняется в админке: «Элементы интерфейса» → «Применить для всей платформы»."}')
ON CONFLICT (key) DO NOTHING;
