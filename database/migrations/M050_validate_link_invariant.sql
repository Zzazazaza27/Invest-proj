-- =============================================================================
-- M050 — проверка накопленных строк по одному из инвариантов M047
--
-- M047 добавила два ограничения как NOT VALID: они действуют для новых и
-- изменяемых строк, но накопленные не перепроверялись. Здесь долг закрывается
-- ровно наполовину — и это сознательно.
--
-- `project_materials_link_is_uploaded` ПРОВЕРЯЕТСЯ: нарушающих строк нет ни
-- одной, значит утверждение «ссылка на продукт всегда загружена» верно для всей
-- таблицы, а не только для будущих записей.
--
-- `project_materials_confirmed_has_size` остаётся NOT VALID. Причина названа
-- числом: 25 презентаций, созданных 9–10 августа, подтверждены без размера —
-- это записи, сделанные до того, как подтверждение стало читать размер из
-- хранилища. Подставить им размер задним числом нельзя: он неизвестен, а
-- выдумать его значит записать в базу число, которого никто не измерял. Так
-- ограничение честно говорит «для новых строк — гарантия, для старых — нет»,
-- вместо того чтобы выглядеть гарантией целиком.
--
-- Что нужно, чтобы закрыть остаток: сверить эти 25 объектов с хранилищем и
-- проставить фактический размер, либо признать их непригодными и убрать. И то и
-- другое — решение владельца данных, а не миграции.
-- =============================================================================

ALTER TABLE lab.project_materials
    VALIDATE CONSTRAINT project_materials_link_is_uploaded;
