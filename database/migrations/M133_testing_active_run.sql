-- M133: «идёт ли такой запуск» — вопрос, на который вправе ответить каждый.
--
-- ЗАЧЕМ. Происхождение записи, которое уборка вправе удалять (`render_check`,
-- `load_test`), до этой миграции назначалось по одному заголовку запроса.
-- Опыт показал, чего это стоит: обычный клиент БЕЗ всякой авторизации
-- регистрировался с `X-Unicorn-Origin: render_check`, и его учётная запись
-- становилась следом прогона — то есть посторонний мог подвести свою запись
-- под уборку или спрятать её из списка пользователей.
--
-- Теперь такое происхождение назначается только вместе с идентификатором
-- ДЕЙСТВУЮЩЕЙ тестовой сессии. Завести её может лишь администратор с
-- полномочием `testing.sessions.manage`.
--
-- ПОЧЕМУ ФУНКЦИЯ, А НЕ ЗАПРОС К ТАБЛИЦЕ. Спрашивает публичный маршрут
-- регистрации: пользователя в запросе ещё нет, а политики `testing.sessions`
-- построены на нём — строка просто не видна, и проверка всегда отвечала бы
-- «нет». Функция отвечает ровно на один вопрос и не раскрывает ничего
-- сверх него: ни заголовка сессии, ни её владельца, ни самого факта
-- существования неактивной. Для постороннего «нет» и «нет такой» неразличимы.
CREATE OR REPLACE FUNCTION testing.is_active_run(p_session_id UUID)
RETURNS BOOLEAN
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
-- pg_temp последним: иначе временная таблица посетителя могла бы подменить
-- собой настоящую (общее правило проекта для функций-владельцев).
SET search_path = testing, pg_temp
AS $$
BEGIN
    RETURN EXISTS (
        SELECT 1 FROM testing.sessions
         WHERE id = p_session_id AND status = 'active'
    );
END;
$$;

COMMENT ON FUNCTION testing.is_active_run(UUID) IS
    'Идёт ли сейчас такой запуск. Единственный способ для публичного маршрута '
    'регистрации убедиться, что право назвать запись следом прогона у клиента '
    'есть. Возвращает только да/нет: существование чужого идентификатора — '
    'тоже сведения.';

GRANT EXECUTE ON FUNCTION testing.is_active_run(UUID) TO app_backend;
