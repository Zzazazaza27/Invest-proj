-- M113 — правило «услугу платформы нельзя закрыть галочкой» должно работать
-- для всех ролей, а не только для тех, кому видно каталог услуг.
--
-- Триггер M111 отвечает на вопрос «кто выполняет эту услугу», заглядывая в
-- `billing.round_services`. Денежному контуру эта таблица была недоступна —
-- и попытка закрыть позицию под ролью `app_billing` падала не по делу:
-- `permission denied for table round_services`. Проверка обязана срабатывать
-- по СМЫСЛУ («разбора не было»), а не по нехватке прав у проверяющего.
--
-- Дано минимальное: чтение каталога. Менять услуги денежный контур не может и
-- не должен — это по-прежнему дело администратора.

GRANT SELECT ON billing.round_services TO app_billing;

CREATE POLICY round_services_billing_read ON billing.round_services FOR SELECT
    TO app_billing USING (true);

COMMENT ON POLICY round_services_billing_read ON billing.round_services IS
    'Денежный контур читает каталог услуг, чтобы правило M111 (услугу платформы закрывает только '
    'успешный разбор) проверялось по смыслу, а не падало на правах (M113).';
