-- =============================================================================
-- M035 — рубеж действительности сессий пользователя
--
-- Находка внешнего аудита (SEC-08): роли берутся из токена, а токен живёт до
-- своего `exp` (по умолчанию час). Снятая в БД роль администратора продолжала
-- действовать до истечения сессии, и `logout` этого не менял — он лишь удалял
-- cookie у клиента, тогда как сам токен оставался валидным.
--
-- Механика исправления — рубеж: токен, выпущенный РАНЬШЕ отметки, недействителен.
-- Это дешевле реестра сессий (одно поле вместо таблицы) и достаточно для
-- главного случая: изменение прав или компрометация обесценивают ВСЕ ранее
-- выданные токены пользователя разом.
--
-- Чего рубеж НЕ делает: он не отзывает отдельный токен, оставляя остальные.
-- Для этого нужен идентификатор токена и его реестр — это остаётся долгом и
-- записано в TODO, а не выдаётся за сделанное.
-- =============================================================================

ALTER TABLE identity.users
    ADD COLUMN IF NOT EXISTS sessions_valid_from TIMESTAMPTZ NOT NULL DEFAULT now();

COMMENT ON COLUMN identity.users.sessions_valid_from IS
    'Рубеж действительности сессий: токен с iat раньше этой отметки отклоняется. '
    'Сдвигается при изменении ролей, смене пароля и выходе из всех сессий (M035).';

-- Сервисные роли читают отметку вместе с остальными полями пользователя;
-- отдельного GRANT не требуется — колонка добавляется в существующую таблицу.
