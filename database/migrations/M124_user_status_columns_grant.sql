-- M124 — права на колонки состояния, добавленные M123.
--
-- Отдельной миграцией, потому что M123 уже применена, а применённые вперёд не
-- переписываются. Тот же порядок, что у M120 → M121.
--
-- Чего не хватило. Права на `identity.users` выданы ПОКОЛОНОЧНО (M056):
-- `GRANT UPDATE (display_name, locale, currency_pref, mfa_enabled, status,
-- updated_at, sessions_valid_from)`. Новая колонка в такой таблице по
-- умолчанию недоступна — и это ровно то поведение, ради которого поколоночные
-- права и вводились: расширение доступа должно быть явным шагом. M123 добавила
-- `status_reason`, `status_changed_at`, `status_changed_by`, но шаг не сделала,
-- и блокировка падала с «permission denied for table users» (поймано живым
-- прогоном, а не чтением кода).
--
-- Что именно разрешается и почему только это: три колонки описывают ПОВОД и
-- АВТОРА смены состояния и меняются той же операцией, что и сам `status`.
-- Ничего сверх них не открывается — `primary_role`, `deleted_at`, контакты и
-- `password_hash` по-прежнему вне досягаемости app_backend.
-- =============================================================================

GRANT UPDATE (status_reason, status_changed_at, status_changed_by)
    ON identity.users TO app_backend;

