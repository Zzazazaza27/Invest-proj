-- M168 — смысл ворот восстановленной среды уточнён (замечание Тэнка 3 к 1a7ef69, 09.11.2026).
--
-- Заголовок M167 утверждал, что любое восстановление меняет отпечаток базы и закрывает
-- среду само. Это неверно: логическое восстановление в ту же базу сохраняет кластер, линию
-- времени и oid. Применённая миграция не правится — верное описание здесь, в комментариях
-- объектов. Поведение не меняется.

COMMENT ON TABLE ops.restore_gate IS
    'Ворота среды (2.1.5). Закрыто, если строка закрыта или её нет, если отпечаток базы не тот, '
    'при котором ворота открыли, или у ядра задано удержание CORE_RESTORE_HOLD. Отпечаток — '
    'дополнительная защита, а не доказательство восстановления: процедура восстановления '
    'закрывает среду явно (удержание и deletions-apply close) и держит запрет до проверки. '
    'Копии pg_dump снимаются без строки ворот.';

COMMENT ON FUNCTION ops.database_fingerprint() IS
    'Кластер, линия времени WAL и oid базы. Меняется при восстановлении в новую базу и при '
    'pgBackRest; НЕ меняется при логическом восстановлении в ту же базу.';
