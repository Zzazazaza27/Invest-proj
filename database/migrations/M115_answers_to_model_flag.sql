-- M115 — условия обработки ответов внешней моделью.
--
-- Ответы анкеты — содержание заявки основателя. В разбор по правилам они
-- входят: считает их НАШ шлюз, наружу ничего не уходит. Отправка их внешней
-- языковой модели — другое действие с другими последствиями: данные покидают
-- периметр, и на это нужны согласованные условия обработки (что отправляем,
-- кому, на каком основании, что провайдер имеет право с этим делать).
--
-- Флаг выключен. Пока он выключен, включённая языковая модель не выполняет
-- разбор вовсе: путь отказывает явно, а не «тихо анализирует без ответов» —
-- иначе отчёт назывался бы анализом заявки, не увидев ни одного ответа.
--
-- Содержимое материалов этим флагом НЕ открывается: в шлюз уходит только тип
-- материала, и это отдельное решение с отдельными правилами.
INSERT INTO audit.feature_flags (key, enabled, rules_jsonb)
VALUES ('ai.answers_to_model.allowed', false,
        '{"note":"Разрешение отправлять ответы анкеты внешней языковой модели (6.1). Выключено: условия обработки не согласованы. Влияет только на LLM-путь; разбор по правилам считает собственный шлюз."}')
ON CONFLICT (key) DO NOTHING;
