-- =============================================================================
-- M044 — отпечаток загруженного объекта: подмена становится обнаружимой
--
-- Находка внешнего аудита (SEC-04). Подписанная форма загрузки действует до
-- истечения и относится к ПОСТОЯННОМУ ключу объекта. Значит, тот же запрос
-- можно отправить второй раз уже ПОСЛЕ подтверждения — и содержимое объекта
-- заменится, а в БД останется запись о прежней загрузке. Фиксировался только
-- размер, который у подменённого файла легко совпадает.
--
-- Что эта миграция делает и чего НЕ делает. Она не предотвращает подмену:
-- предотвращает её версионирование бакета и Object Lock, то есть настройка
-- хранилища, а не колонка в таблице. Она делает подмену ОБНАРУЖИМОЙ — отпечаток
-- объекта на момент подтверждения сохраняется, и любая последующая сверка
-- покажет расхождение. Это половина защиты, и она названа половиной, а не выдана
-- за целое; вторая половина — в TODO как настройка хранилища.
-- =============================================================================

ALTER TABLE lab.project_materials
    ADD COLUMN IF NOT EXISTS content_hash TEXT;

COMMENT ON COLUMN lab.project_materials.content_hash IS
    'Отпечаток объекта (ETag) на момент подтверждения загрузки. Не предотвращает '
    'подмену объекта повторной отправкой подписанной формы, но делает её '
    'обнаружимой сверкой (SEC-04, M044).';
