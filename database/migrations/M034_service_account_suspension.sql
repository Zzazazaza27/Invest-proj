-- =============================================================================
-- M034 — журнальные глаголы приостановки сервисного аккаунта
--
-- Находка внешнего аудита (SEC-07): выдача токена искала учётную запись по
-- `client_id` без учёта статуса, поэтому приостановленный аккаунт продолжал
-- получать токены. Статус в таблице был, но не значил ничего — приостановка
-- существовала только на бумаге.
--
-- Проверка статуса добавлена в выборку, но одной её мало: приостанавливать
-- было НЕЧЕМ — административного действия не существовало. Здесь регистрируются
-- глаголы для него; сам маршрут — в `service-accounts.controller.ts`.
--
-- Почему это отдельные глаголы, а не «изменение аккаунта»: приостановка доступа
-- внешней системы — событие, которое ищут в журнале по названию, когда
-- разбирают инцидент.
-- =============================================================================

INSERT INTO audit.event_type_registry (verb, description, actor_roles_allowed) VALUES
    ('integration.service_account.suspended', 'Приостановлен сервисный аккаунт интеграции', ARRAY['admin']),
    ('integration.service_account.resumed',   'Возобновлён сервисный аккаунт интеграции',  ARRAY['admin'])
ON CONFLICT (verb) DO NOTHING;
