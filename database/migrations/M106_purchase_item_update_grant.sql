-- M106 — право менять состояние выполнения услуги по покупке.
--
-- В M095 позиции покупки были неизменяемы полностью, поэтому UPDATE на них
-- никому не выдавался. С M103 у позиции появилось состояние работы
-- («запланировано / в работе / выполнено / не выполнено»), и его ставит
-- сотрудник платформы.
--
-- Денежные поля позиции по-прежнему не меняются — это держит триггер
-- `forbid_purchase_item_rewrite`; право UPDATE открывает только состояние
-- работы, а политика RLS оставляет его администратору.
GRANT UPDATE ON billing.round_purchase_items TO app_backend;
