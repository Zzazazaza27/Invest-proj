-- =============================================================================
-- M031 — индекс под фактический порядок каталога
--
-- Находка замера на 20 000 проектов: основной запрос каталога
-- (`listing_status = 'listed' AND deleted_at IS NULL ORDER BY listed_at DESC,
-- id DESC`) шёл последовательным чтением с последующей сортировкой всех
-- отобранных строк. Существующий `projects_catalog (listing_status,
-- taxonomy_id, listed_at DESC)` для него не подходит: `taxonomy_id` стоит
-- между условием и порядком, а запрос без фильтра по направлению — самый
-- частый (первая страница витрины).
--
-- На 20 тысячах это 15 мс и внимания не привлекает. Проблема в том, что
-- стоимость растёт вместе с каталогом: сортируется весь отобранный набор, а не
-- страница. Индекс под ключевой набор (keyset) делает выборку страницы
-- независимой от размера каталога.
--
-- Частичный: строки не опубликованные и удалённые в каталоге не участвуют
-- никогда, и держать их в индексе незачем.
-- =============================================================================
-- migrate:no-transaction

CREATE INDEX CONCURRENTLY IF NOT EXISTS projects_catalog_keyset
    ON lab.projects (listed_at DESC, id DESC)
    WHERE listing_status = 'listed' AND deleted_at IS NULL;

COMMENT ON INDEX lab.projects_catalog_keyset IS
    'Порядок первой страницы каталога и переход по курсору (listed_at, id). '
    'Частичный: неопубликованные и удалённые проекты в каталог не попадают.';
