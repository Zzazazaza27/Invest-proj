-- =============================================================================
-- M061 — флаг приёма платежей
--
-- Клиент вызывает `POST /v1/billing/payments` с самого начала, а контроллера с
-- таким маршрутом в ядре нет: проверено вызовом против живого ядра — **404**.
-- Это тот же класс расхождения, что закрыт в Ф50 для согласий на публикацию, и
-- нашёлся он так же — прогоном, а не чтением кода.
--
-- Разница в том, что там не хватало ровно контроллера, а здесь не хватает
-- ВНЕШНЕГО КОНТРАГЕНТА: платёжный провайдер не выбран, договора нет, вебхука
-- подтверждения нет. Написать «оплату», которая создаёт запись в
-- `billing.payments` и рапортует об успехе, значило бы завести в денежной
-- таблице строки, за которыми не стоит ни одного перевода.
--
-- Поэтому маршрут появляется, но выключен флагом — тем же способом, каким в
-- проекте уже выключен регулируемый контур (`investments.enabled`, M011).
-- Разница между «маршрута нет» и «маршрут есть и говорит, что канал не
-- подключён» — это разница между ловушкой и честным состоянием продукта.
--
-- Флаг включается, когда появятся: договор с провайдером, его учётные данные,
-- обработчик вебхука подтверждения и решение о том, кто сверяет поступления.
-- =============================================================================

INSERT INTO audit.feature_flags (key, enabled, rules_jsonb) VALUES
    ('billing.payments.enabled', false,
     '{"requires":"платёжный провайдер: договор, ключи, вебхук подтверждения",
       "note":"счёт оплачивается по реквизитам, поступление сверяет оператор"}')
ON CONFLICT (key) DO NOTHING;
