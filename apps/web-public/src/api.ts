import { UnicornApi } from '@unicorn/api-client';

/**
 * Единственная точка связи витрины с бэкендом.
 *
 * Витрина анонимна: ни сессии, ни токена здесь нет и быть не должно — всё, что
 * она показывает, доступно публично по построению (тизеры листингов, тарифы,
 * метроном сезона). Появление здесь аутентификации означало бы, что витрина
 * начала показывать чужие данные.
 */
const baseUrl = import.meta.env.VITE_API_BASE_URL ?? 'http://localhost:4300/v1';

export const api = new UnicornApi({
  baseUrl,
  auth: { kind: 'none' },
  // Витрина — первое, что видит человек. Запрос, висящий дольше десяти секунд,
  // для него неотличим от сломанного сайта.
  timeoutMs: 10_000,
});

export { ApiError } from '@unicorn/api-client';
