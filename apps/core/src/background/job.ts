/**
 * Описание фоновой задачи и результат её прохода (блок 1, 1.2).
 *
 * Прикладное действие остаётся в своём доменном модуле; здесь только то, что
 * нужно общему механизму, чтобы запускать, координировать и останавливать.
 */

/**
 * Как задача делит работу между экземплярами core.
 *
 *  - `local` — координация внутри самой задачи: аренда строк её записей
 *    (публикатор, доставка вебхуков, будущие загрузки). Проход запускается в
 *    каждом экземпляре, а строки разбираются арендой.
 *  - `advisory` — обслуживание без записей работы: в каждый момент проход
 *    выполняет один экземпляр, удерживающий advisory-блокировку PostgreSQL по
 *    ключу имени задачи. Остальные пропускают проход.
 */
export type JobCoordination = 'local' | 'advisory';

/**
 * Явный результат прохода.
 *
 * Ошибка — не результат, а исключение: задача бросает его наружу, и оболочка
 * записывает проход как неудачный. Перехват с возвратом нуля делал отказ
 * неотличимым от «работы не было».
 */
export type JobResult = { status: 'done'; processed: number } | { status: 'idle' };

export interface JobContext {
  readonly name: string;
  /**
   * Прерывается сигналом остановки процесса либо потерей advisory-блокировки.
   *
   * Задача проверяет его перед каждой самостоятельной операцией — следующей
   * записью пачки, следующим внешним действием — и после прерывания новых не
   * начинает. Уже начатую операцию доводит до конца.
   */
  readonly signal: AbortSignal;
}

export interface JobDefinition {
  /** Стабильное имя: по нему выключатель, ключ блокировки и строка в /jobs. */
  readonly name: string;
  readonly intervalMs: number;
  readonly coordination: JobCoordination;
  /** Первый проход сразу после старта, а не через интервал. */
  readonly runAtStart?: boolean;
  /**
   * Проход делает что-то за пределами платформы (письмо, вебхук). При закрытых воротах
   * восстановленной среды (2.1.5, M167) такой проход не запускается: восстановленные
   * письма и доставки не уходят до применения учёта удалений — независимо от HTTP.
   */
  readonly externalEffects?: boolean;
  run(ctx: JobContext): Promise<JobResult>;
}

/** Число обработанного → результат: ноль означает «работы не было». */
export function resultOf(processed: number): JobResult {
  return processed > 0 ? { status: 'done', processed } : { status: 'idle' };
}
