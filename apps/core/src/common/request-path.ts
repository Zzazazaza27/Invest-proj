/**
 * Нормализованный путь запроса для классификации ограничения частоты.
 *
 * Живёт отдельным модулем, а не внутри `main.ts`: тот при импорте поднимает
 * приложение (`void bootstrap()`), поэтому импортировать из него функцию в
 * тест нельзя — а функция, определяющая класс лимита, обязана быть покрыта
 * тестами.
 *
 * Берёт часть до `?` и декодирует percent-encoding многократно, до
 * стабилизации: двойное кодирование (`%2561` → `%61` → `a`) тоже сводится к
 * канонической форме. Fastify маршрутизирует по ДЕКОДИРОВАННОМУ пути, поэтому
 * классификатор обязан видеть тот же путь, что и роутер: иначе
 * `POST /v1/%61uth/login` доходит до обработчика входа, но класс auth (30/мин)
 * не распознаётся и применяется default (120/мин) — четырёхкратное ослабление
 * единственной защиты от перебора пароля (HIGH внешнего аудита №2). То же
 * уводило денежные маршруты из 10/мин в общий класс.
 *
 * Некорректная кодировка (`%zz`) наружу не бросается: возвращается то, что
 * удалось раскодировать на предыдущем шаге. Ошибка декодирования не должна
 * открывать обход — она должна оставлять путь максимально «раскрытым».
 *
 * Регистр приводится к нижнему: сравнение классов идёт по литералам в нижнем
 * регистре, а `/V1/AUTH/LOGIN` — тот же маршрут для роутера.
 */
export function normalizedPath(rawUrl: string): string {
  let path = (rawUrl.split('?', 1)[0] ?? '').toLowerCase();
  for (let i = 0; i < 5 && path.includes('%'); i += 1) {
    let decoded: string;
    try {
      decoded = decodeURIComponent(path);
    } catch {
      break;
    }
    if (decoded === path) break;
    path = decoded.toLowerCase();
  }
  return path;
}

/**
 * Класс ограничения частоты по нормализованному пути и методу.
 *
 * Вынесен сюда и используется В ДВУХ местах — при выборе порога и при
 * построении ключа ведра. Это не удобство, а исправление конкретного дефекта.
 *
 * Плагин ограничения частоты держит ОДИН счётчик на ключ, а порог вычисляет на
 * каждый запрос. Пока ключ не зависел от класса, все запросы пользователя
 * падали в одно ведро, и первая же денежная операция сравнивалась с порогом 10
 * при счётчике, набитом обычными чтениями кабинета. Воспроизведено: одиннадцать
 * безобидных чтений, затем ПЕРВОЕ оформление подписки — **429** (денежный
 * класс удалён в 2.1-W05 вместе с платежами; правило ключа осталось). То есть «денежный класс 10/мин» на деле означал «любые десять
 * запросов, и деньги закрыты на минуту».
 *
 * Теперь класс входит в ключ, и у каждого класса свой счётчик — ровно то, что
 * и описывалось в комментариях с самого начала.
 */
export type RateLimitClass = 'auth' | 'admin' | 'default';

/**
 * Чтения собственной сессии. Секрета не принимают и подбору не подлежат:
 * без действующей cookie отвечают 401 сразу, с ней — рассказывают о себе же.
 *
 * Держатся списком, а не правилом «любой GET под /v1/auth/»: под тем же
 * префиксом есть GET с одноразовым токеном в запросе (`email/verify/status`),
 * и он обязан оставаться в жёстком классе.
 */
const SESSION_READS = new Set(['/v1/auth/me', '/v1/auth/authz/console']);

export function rateLimitClass(normalized: string, method: string): RateLimitClass {
  const isMutation = method !== 'GET' && method !== 'HEAD';

  // Проверка сессии — не попытка входа.
  //
  // Порог auth (30/мин) считается ПО АДРЕСУ, одним ведром на всю машину. Пока
  // сюда попадал `GET /v1/auth/me`, обычная работа человека упиралась в него
  // сама: каждый кабинет спрашивает профиль при загрузке страницы, вкладок
  // несколько, перезагрузок за минуту тоже. Итог — 429 на проверке сессии,
  // который интерфейс показывал как выход из аккаунта (проход 7.4).
  //
  // Это не ослабление защиты от перебора: перебирать здесь нечего. Все
  // маршруты, где проверяется секрет (вход, регистрация, сброс и смена
  // пароля, выдача сервисного токена), — POST, и они остаются в auth.
  if (!isMutation && SESSION_READS.has(normalized)) return 'default';

  // Выдача сервисного токена — тот же класс, что и вход человека: это проверка
  // секрета, и перебор по ней ограничивается так же жёстко.
  if (normalized.startsWith('/v1/auth/') || normalized.startsWith('/v1/integration/token')) {
    return 'auth';
  }

  // Административные операции чувствительны, поэтому лимит ниже общего:
  // оператор за минуту делает и просмотры, и несколько изменений подряд.
  if (normalized.startsWith('/v1/admin/')) return 'admin';

  return 'default';
}
