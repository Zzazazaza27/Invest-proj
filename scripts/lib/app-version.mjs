import { execFileSync } from 'node:child_process';

/**
 * Версия сборки для сообщений об ошибках.
 *
 * Нужна ровно в одном месте: в техническом контексте баг-репорта. Без неё
 * сообщение «не открывается карточка» невозможно привязать к коду — на стенде
 * и в production крутятся разные сборки, и «сейчас работает» ничего не значит.
 *
 * Источник — короткий hash коммита. Он берётся ОДИН РАЗ на сборку и попадает в
 * бандл константой: запрашивать его в браузере неоткуда, а тянуть отдельным
 * маршрутом ради одной строки — лишний вызов на каждой странице.
 *
 * Отсутствие git не является ошибкой сборки. Артефакт собирают и из архива без
 * `.git` (контейнер, выгрузка релиза), и падение сборки из-за справочной
 * строки было бы хуже самой пропажи: тогда вместо версии подставляется
 * `unknown`, и это видно в отчёте как есть, а не изображается версией.
 *
 * `GIT_COMMIT` перекрывает git: в CI рабочее дерево часто detached или мелкое,
 * а идентификатор коммита система сборки знает и так.
 */
export function appVersion() {
  const fromEnv = process.env.GIT_COMMIT ?? process.env.VITE_APP_VERSION;
  if (fromEnv && fromEnv.trim() !== '') return fromEnv.trim().slice(0, 40);
  try {
    // execFileSync, а не exec: аргументы не проходят через оболочку, и
    // подставить сюда что-либо через переменную окружения нельзя.
    return execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    })
      .trim()
      .slice(0, 40);
  } catch {
    return 'unknown';
  }
}
