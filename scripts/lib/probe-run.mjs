/**
 * Учёт людей, которых заводит браузерный прогон.
 *
 * ЗАЧЕМ. Проверки регистрировали себе учётные записи обычной регистрацией —
 * без единого признака, что это след прогона. За неделю список пользователей
 * переставал рассказывать о платформе и начинал рассказывать о наших
 * проверках; фильтр «без записей проверок» их не прятал, уборка не находила,
 * а однажды длинные имена вроде «Сотрудник conflict 73671257» уронили
 * проверку плотности таблицы.
 *
 * ТРИ РАЗНЫЕ ВЕЩИ, и пометка закрывает только первую:
 *
 *   1. ПРОИСХОЖДЕНИЕ — «это завёл прогон, а не человек». Заголовок
 *      `X-Unicorn-Origin` (M127). Доверять ему можно потому, что в боевом
 *      контуре он игнорируется целиком, а вне его список значений закрыт.
 *   2. ПРИНАДЛЕЖНОСТЬ — «завёл вот ЭТОТ запуск вот ЭТОЙ проверки». Здесь она
 *      ведётся самим прогоном: имя запуска попадает в отображаемое имя, а
 *      список созданного — в память прогона.
 *   3. ОЧИСТКА — успешный прогон убирает за собой, упавший оставляет данные
 *      для разбора и печатает, по какому признаку их искать.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Серверного учёта принадлежности к запуску: у механизма
 * тестовых сессий он есть, но сессия выдаёт только роли founder, expert и
 * investor, а большинство браузерных проходов заводит себе АДМИНИСТРАТОРА.
 * Пока это так, принадлежность держится на самом прогоне.
 *
 * УБОРКА ПОМЕЧАЕТ, А НЕ УДАЛЯЕТ — и это не осторожность. На `identity.users`
 * ссылаются 46 внешних ключей, ни один не объявляет ON DELETE, а акцепты
 * согласий неизменяемы (M002): физически удалить человека схема не даёт. То
 * же решение принято в `clean-probe-data`.
 */

/** Одно значение на все браузерные проходы: его знает уборка следов (M127). */
export const PROBE_ORIGIN = 'render_check';

/**
 * Завести учёт для одного запуска проверки.
 *
 * @param {string} probeId идентификатор проверки в реестре, например RND-LAB
 * @param {(text: string, params?: unknown[]) => Promise<unknown[]>} sql доступ к базе
 */
export function startProbeRun(probeId, sql) {
  // Метка запуска: по ней видно, какой именно прогон оставил записи, если он
  // упал и данные остались для разбора.
  const runId = `${probeId}-${Date.now().toString(36)}`;
  const users = [];

  return {
    runId,

    /** Заголовки регистрации: происхождение называется серверу явно. */
    headers() {
      return { 'Content-Type': 'application/json', 'X-Unicorn-Origin': PROBE_ORIGIN };
    },

    /** Запомнить заведённого человека, чтобы было что убирать. */
    track(userId) {
      if (userId) users.push(userId);
      return userId;
    },

    /** Сколько людей завёл этот запуск. */
    get created() {
      return users.length;
    },

    /**
     * Убрать за собой — ТОЛЬКО при успехе.
     *
     * Данные упавшего прогона и есть материал разбора: удалить их значит
     * лишиться единственного свидетельства. Поэтому при неуспехе печатается,
     * по какому признаку записи искать.
     */
    async finish(ok) {
      if (users.length === 0) return;
      if (!ok) {
        console.warn(
          `\n  данные оставлены для разбора: запуск ${runId}, ` +
            `людей ${users.length}, происхождение ${PROBE_ORIGIN}`,
        );
        return;
      }
      await sql(
        `UPDATE identity.users SET deleted_at = now()
          WHERE id = ANY($1::uuid[]) AND deleted_at IS NULL`,
        [users],
      );
      console.warn(`\n  прогон убрал за собой: людей ${users.length}`);
    },
  };
}
