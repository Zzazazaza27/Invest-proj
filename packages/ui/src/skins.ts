/**
 * Реестр подключённых скинов платформы.
 *
 * Скин — набор значений токенов `--u-*`, включаемый атрибутом `data-brand` на
 * элементе: на корне страницы — для всего приложения, на отдельном блоке —
 * только для него (так работает предпросмотр в админке, «Элементы
 * интерфейса»). Компоненты о скинах не знают: они читают те же переменные.
 *
 * Подключить новый скин:
 *   1. файл `theme-<id>.css` с блоком `[data-brand='<id>'] { --u-…: … }`
 *      (образец — `theme-nova.css`) и экспорт в `package.json`;
 *   2. импорт этого файла в `apps/admin/src/main.tsx` — чтобы его видел
 *      предпросмотр;
 *   3. строка здесь.
 *
 * Список описывает только то, что реально подключено. Выдуманный скин ради
 * переключателя показывал бы значения, которых нет ни в одном приложении.
 */
export interface Skin {
  /** Значение атрибута `data-brand`. */
  id: string;
  title: string;
  /** Где объявлены значения — чтобы было понятно, что править. */
  source: string;
}

