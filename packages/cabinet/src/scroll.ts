import { useEffect, useRef } from 'react';

/**
 * Вернуть прокрутку к началу, когда сменился экран.
 *
 * Зачем нужно. В одностраничном приложении переход по меню меняет
 * содержимое, но НЕ трогает прокрутку: браузер справедливо считает, что
 * страница та же. Человек, читавший середину длинного экрана, переключает
 * раздел и видит новый — сразу с середины, без заголовка. Выглядит как
 * «страница открылась сломанной».
 *
 * Почему хук, а не готовый `ScrollRestoration` из маршрутизатора: тот
 * работает только с data-router'ом, а кабинеты устроены по-разному. У
 * администратора и основателя экраны — маршруты, у других — разделы в
 * состоянии. Общее у них одно: ЗНАЧЕНИЕ, которое
 * меняется при смене экрана. Его хук и принимает, оставаясь без зависимости
 * от react-router — пакет кабинетных блоков её не имеет и иметь не должен.
 *
 * Первый рендер намеренно пропускается: прокручивать только что открытую
 * страницу незачем, а при переходе по ссылке с якорем это ещё и отняло бы у
 * человека то место, куда он шёл.
 */
export function useScrollToTopOnChange(screenKey: string | number | boolean): void {
  const previous = useRef(screenKey);

  useEffect(() => {
    if (previous.current === screenKey) return;
    previous.current = screenKey;
    // Якорь в адресе — это просьба показать конкретное место; перебивать её
    // прокруткой к началу нельзя.
    if (typeof window !== 'undefined' && window.location.hash.length > 1) return;
    window.scrollTo({ top: 0, left: 0, behavior: 'auto' });
  }, [screenKey]);
}
